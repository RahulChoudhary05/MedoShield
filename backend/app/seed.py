"""Demo data for local development (in-memory DB) or when SEED_DEMO_DATA=true.

Creates a care team, one demo patient with ~5 weeks of movement checks generated by
running *real* synthetic pose sequences through the analytics engine, plus
medications, lifestyle logs and a chat thread. Idempotent.
"""
from __future__ import annotations

import logging
import random
from datetime import timedelta

from bson import ObjectId

from app.ai_engine import analyze, build_baseline, classify, deviation, features_dict, motor_index
from app.core.config import settings
from app.core.security import hash_password, utcnow
from app.core.utils import mongo_safe
from app.db.database import get_db

log = logging.getLogger("medoshield.seed")

DEMO_PATIENT_EMAIL = "demo.patient@medoshield.dev"
DOCTORS = [
    ("Sarah", "Johnson", "sarah.johnson@medoshield.dev", "Neurologist", "Neuro Care Clinic", 12, 4.9, 600,
     "Movement-disorder specialist focused on early Parkinson's care and tremor management."),
    ("Michael", "Chen", "michael.chen@medoshield.dev", "Physiotherapist", "Movement Therapy Center", 8, 4.8, 400,
     "Gait retraining, fall prevention and LSVT-BIG certified therapy."),
    ("Ananya", "Rao", "ananya.rao@medoshield.dev", "General Practitioner", "Lotus Family Health", 10, 4.7, 300,
     "Whole-person primary care with a focus on chronic-condition coaching."),
    ("Emily", "Watson", "emily.watson@medoshield.dev", "Cardiologist", "Cardiac Health Institute", 15, 4.8, 700,
     "Preventive cardiology and blood-pressure management."),
    ("James", "Rodriguez", "james.rodriguez@medoshield.dev", "Therapist", "Mindful Wellness Clinic", 9, 4.6, 350,
     "CBT for health anxiety, stress and sleep."),
]


def demo_password() -> str:
    return settings.DEMO_PASSWORD or "Demo@Medo2026!"


async def seed_demo() -> None:
    db = get_db()
    if await db["patients"].find_one({"email": DEMO_PATIENT_EMAIL}):
        return
    if settings.is_production and not settings.DEMO_PASSWORD:
        log.warning("SEED_DEMO_DATA ignored: set DEMO_PASSWORD to seed demo accounts in production")
        return
    from app.ai_engine.synthetic import make_frames

    now = utcnow()
    pw = hash_password(demo_password())
    doctor_ids = []
    for first, last, email, spec, clinic, yrs, rating, fee, bio in DOCTORS:
        existing = await db["doctors"].find_one({"email": email})
        if existing:
            doctor_ids.append(str(existing["_id"]))
            continue
        res = await db["doctors"].insert_one({
            "doctor_id": f"DOC-{ObjectId()}", "first_name": first, "last_name": last, "email": email, "password_hash": pw,
            "specialty": spec, "clinic_name": clinic, "license_number": f"MCI-{random.randint(10000, 99999)}",
            "appointment_fee": fee, "experience_years": yrs, "rating": rating, "bio": bio, "accepting_patients": True,
            "license_verified": True, "is_active": True, "created_at": now, "updated_at": now,
        })
        doctor_ids.append(str(res.inserted_id))

    pres = await db["patients"].insert_one({
        "user_id": str(ObjectId()), "first_name": "Arjun", "last_name": "Mehta", "email": DEMO_PATIENT_EMAIL,
        "date_of_birth": "1961-04-18", "gender": "M", "phone": "+91 98200 11223",
        "medical_history": "Mild right-hand tremor noticed 2025. Hypertension, well controlled.",
        "conditions": ["Hypertension", "Early Parkinson's (under evaluation)"], "allergies": ["Penicillin"],
        "current_medications": ["Amlodipine 5 mg"], "emergency_contact_name": "Priya Mehta", "emergency_contact_phone": "+91 98200 44556",
        "hashed_password": pw, "is_active": True, "created_at": now - timedelta(days=40), "updated_at": now,
    })
    pid = str(pres.inserted_id)
    neuro, physio = doctor_ids[0], doctor_ids[1]

    for d, unlocked in ((neuro, True), (physio, False)):
        await db["patient_doctor_assignments"].insert_one({"patient_id": pid, "doctor_id": d, "assigned_at": now - timedelta(days=30),
                                                           "is_active": True, "is_video_analysis_unlocked": unlocked, "source": "appointment"})
    await db["appointment_requests"].insert_many([
        {"doctor_id": neuro, "patient_id": pid, "preferred_date": (now - timedelta(days=31)).date().isoformat(), "preferred_time": "10:30",
         "meeting_mode": "video_call", "message": "Right-hand tremor for a few months.", "status": "accepted", "appointment_fee": 600,
         "created_at": now - timedelta(days=32), "updated_at": now - timedelta(days=31)},
        {"doctor_id": neuro, "patient_id": pid, "preferred_date": (now + timedelta(days=4)).date().isoformat(), "preferred_time": "11:00",
         "meeting_mode": "video_call", "message": "Follow-up on movement trend.", "status": "pending", "appointment_fee": 600,
         "created_at": now - timedelta(days=1), "updated_at": now - timedelta(days=1)},
    ])

    # ~12 movement checks over 5 weeks; tremor slowly emerges in the last two weeks.
    feats_hist = []
    rng = random.Random(7)
    for i in range(12):
        when = now - timedelta(days=36 - i * 3, hours=rng.randint(0, 6))
        amp = 0.0 if i < 7 else 0.0012 + 0.0007 * (i - 7)
        frames = make_frames(tremor_hz=5.2 if amp else 0, tremor_amp=amp, step_hz=0.92 - 0.012 * max(0, i - 6), seed=100 + i)
        feats, q = analyze(frames)
        f, mi = features_dict(feats), motor_index(feats)
        n_base = settings.BASELINE_SESSIONS
        base = build_baseline(feats_hist[:n_base]) if len(feats_hist) >= n_base else None
        dev = deviation(f, base)
        risk = classify(mi, dev["score"], q.score)
        sres = await db["analysis_sessions"].insert_one(mongo_safe({
            "patient_id": pid, "task": "walk", "video_duration": q.duration_s, "frame_count": q.frames,
            "extracted_features": {**f, "deviation_from_baseline": dev["score"], "risk_score": risk["score"], "risk_level": risk["classification"]},
            "quality": {**q.__dict__, "score": q.score}, "created_at": when, "updated_at": when}))
        await db["risk_assessments"].insert_one(mongo_safe({"patient_id": pid, "session_id": str(sres.inserted_id),
                                                            "risk_score": {**risk, "motor_index": mi, "deviation": dev},
                                                            "flagged_for_review": risk["should_flag"], "created_at": when}))
        feats_hist.append(f)
        if len(feats_hist) == settings.BASELINE_SESSIONS:
            await db["baselines"].insert_one(mongo_safe({"patient_id": pid, "model": build_baseline(feats_hist), "is_calibrated": True, "calibrated_at": when}))

    await db["medication_reminders"].insert_one({"patient_id": pid, "is_active": True, "created_at": now, "updated_at": now, "medications": [
        {"name": "Amlodipine", "dosage": "5 mg", "frequency": "once daily", "time_slots": ["08:00"], "instructions": "After breakfast",
         "added_by": "doctor", "added_by_name": "Dr. Sarah Johnson", "active": True, "side_effects": ["Ankle swelling"]},
        {"name": "Vitamin D3", "dosage": "1000 IU", "frequency": "once daily", "time_slots": ["13:00"], "instructions": "With lunch",
         "added_by": "patient", "added_by_name": "You", "active": True, "side_effects": []},
        {"name": "Magnesium glycinate", "dosage": "200 mg", "frequency": "at night", "time_slots": ["21:30"], "instructions": "For sleep quality",
         "added_by": "doctor", "added_by_name": "Dr. Sarah Johnson", "active": True, "side_effects": []},
    ]})
    for d in range(14):
        day = now - timedelta(days=d)
        for name, slot in (("Amlodipine", "08:00"), ("Vitamin D3", "13:00"), ("Magnesium glycinate", "21:30")):
            if rng.random() < 0.86 and d > 0:
                await db["medication_logs"].insert_one({"patient_id": pid, "medication_name": name, "time_slot": slot, "status": "taken",
                                                        "taken_at": day.replace(hour=int(slot[:2]), minute=int(slot[3:]))})
        await db["fitness_records"].insert_one({
            "patient_id": pid, "date": day.date().isoformat(), "bmi": round(24.6 - d * 0.02, 1), "stress_level": rng.randint(3, 6),
            "walking_distance": round(3.2 + rng.random() * 2.6 + (14 - d) * 0.05, 1), "heart_rate": rng.randint(66, 78),
            "sleep_hours": round(6.1 + rng.random() * 1.8, 1), "notes": "", "created_at": day})

    await db["chat_messages"].insert_many([
        {"patient_id": pid, "doctor_id": neuro, "sender_id": neuro, "sender_role": "doctor", "msg_type": "text", "read_by_patient": True, "read_by_doctor": True,
         "content": "Hi Arjun, I've reviewed your last few movement checks. Could you record one walking check each morning this week?", "created_at": now - timedelta(days=2, hours=3)},
        {"patient_id": pid, "doctor_id": neuro, "sender_id": "demo", "sender_role": "patient", "msg_type": "text", "read_by_patient": True, "read_by_doctor": False,
         "content": "Sure doctor. The shaking is a bit more noticeable when I'm tired in the evening.", "created_at": now - timedelta(days=2, hours=1)},
        {"patient_id": pid, "doctor_id": neuro, "sender_id": neuro, "sender_role": "doctor", "msg_type": "text", "read_by_patient": False, "read_by_doctor": True,
         "content": "That's useful, thank you. I've unlocked AI video review â€” please upload a 10-second clip of you holding your arms out.", "created_at": now - timedelta(hours=20)},
    ])
    await db["notifications"].insert_many([
        {"patient_id": pid, "title": "AI video review unlocked", "message": "Dr. Sarah Johnson enabled AI video movement review for you.", "category": "video", "is_read": False, "created_at": now - timedelta(hours=20)},
        {"patient_id": pid, "title": "Baseline calibrated", "message": "Your personal movement baseline is ready - future checks compare against you.", "category": "risk", "is_read": True, "created_at": now - timedelta(days=22)},
    ])
    log.info("Seeded demo data: patient %s / doctors *@medoshield.dev (password from DEMO_PASSWORD)", DEMO_PATIENT_EMAIL)

