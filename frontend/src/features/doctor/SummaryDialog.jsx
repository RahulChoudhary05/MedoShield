import { useEffect } from 'react'
import { useMutation, useQueryClient } from '@tanstack/react-query'
import { motion } from 'framer-motion'
import { Copy, Lightbulb, ListChecks, RefreshCw, Sparkles } from 'lucide-react'
import { toast } from 'sonner'
import { api } from '../../lib/api'
import { fmtDate } from '../../lib/utils'
import Button from '../../components/ui/Button'
import Dialog from '../../components/ui/Dialog'
import { Badge } from '../../components/ui/Badge'
import { ErrorState, Skeleton } from '../../components/ui/Feedback'

/** Generates a clinician-facing AI summary when opened. */
export default function SummaryDialog({ open, onOpenChange, patientId, name }) {
  const qc = useQueryClient()
  const gen = useMutation({
    mutationFn: () => api.doctors.summary(patientId),
    onSuccess: () => qc.invalidateQueries({ queryKey: ['doctor', 'timeline', patientId] }),
  })
  const { mutate, data, isIdle } = gen

  useEffect(() => {
    if (open && isIdle) mutate()
  }, [open, isIdle, mutate])

  const copy = async () => {
    if (!data) return
    const text = [
      `Clinical summary — ${name}`,
      '',
      data.summary,
      '',
      'Key findings:',
      ...(data.key_findings || []).map((f) => `• ${f}`),
      '',
      'Recommendations:',
      ...(data.recommendations || []).map((f) => `• ${f}`),
    ].join('\n')
    try {
      await navigator.clipboard.writeText(text)
      toast.success('Summary copied')
    } catch {
      toast.error('Couldn’t access the clipboard')
    }
  }

  return (
    <Dialog
      open={open}
      onOpenChange={onOpenChange}
      size="lg"
      title="AI clinical summary"
      description={`Monitoring overview for ${name}. Decision support only — not a diagnosis.`}
      footer={
        <>
          <Button variant="ghost" size="sm" icon={Copy} onClick={copy} disabled={!data}>Copy</Button>
          <Button variant="outline" size="sm" icon={RefreshCw} loading={gen.isPending} onClick={() => gen.mutate()}>Regenerate</Button>
          <Button variant="primary" size="sm" onClick={() => onOpenChange(false)}>Done</Button>
        </>
      }
    >
      {gen.isPending ? (
        <div className="space-y-4" aria-busy="true" aria-live="polite">
          <p className="flex items-center gap-2 text-sm text-teal-700"><Sparkles className="h-4 w-4 animate-pulse" /> Reading movement trends, medications and reports…</p>
          <Skeleton className="h-20" />
          <div className="grid gap-4 sm:grid-cols-2"><Skeleton className="h-32" /><Skeleton className="h-32" /></div>
        </div>
      ) : gen.isError ? (
        <ErrorState error={gen.error} onRetry={() => gen.mutate()} />
      ) : data ? (
        <motion.div initial={{ opacity: 0, y: 8 }} animate={{ opacity: 1, y: 0 }} className="space-y-5">
          <div className="flex flex-wrap items-center gap-2">
            <Badge tone={data.source === 'model' ? 'teal' : 'ink'} dot>{data.source === 'model' ? 'Generated by AI model' : 'Rule-based summary'}</Badge>
            {data.created_at && <span className="text-xs text-ink-4">{fmtDate(data.created_at, 'd MMM yyyy, HH:mm')}</span>}
          </div>
          <p className="rounded-2xl bg-cream px-4 py-3.5 text-[0.9375rem] leading-relaxed text-ink-2 text-pretty">{data.summary}</p>
          <div className="grid gap-4 sm:grid-cols-2">
            <List icon={ListChecks} title="Key findings" items={data.key_findings} tone="bg-teal-50 text-teal-700" />
            <List icon={Lightbulb} title="Recommendations" items={data.recommendations} tone="bg-apricot-50 text-apricot-600" />
          </div>
        </motion.div>
      ) : null}
    </Dialog>
  )
}

function List({ icon: Icon, title, items = [], tone }) {
  return (
    <div className="rounded-2xl border border-line/80 p-4">
      <h4 className="mb-3 flex items-center gap-2 text-sm font-semibold"><span className={`grid h-7 w-7 place-items-center rounded-lg ${tone}`}><Icon className="h-3.5 w-3.5" /></span>{title}</h4>
      {items.length ? (
        <ul className="space-y-2">
          {items.map((t, i) => (
            <li key={i} className="flex gap-2.5 text-sm text-ink-2"><span className="num mt-px text-xs font-semibold text-ink-4">{i + 1}</span><span className="text-pretty">{t}</span></li>
          ))}
        </ul>
      ) : <p className="text-sm text-ink-4">Nothing noted.</p>}
    </div>
  )
}
