import { useEffect } from 'react'
import { useMutation, useQueryClient } from '@tanstack/react-query'
import { motion } from 'framer-motion'
import { Copy, Lightbulb, ListChecks, RefreshCw, Sparkles } from 'lucide-react'
import { toast } from 'sonner'
import { api } from '../../lib/api'
import { fmtDate } from '../../lib/utils'
import Button from '../../components/ui/Button'
import Dialog from '../../components/ui/Dialog'
import { Badge } from '../../components/ui/Badge'
import { ErrorState, Skeleton } from '../../components/ui/Feedback'
import { Label } from './shared'

/** Generates a clinician-facing AI summary when opened. */
export default function SummaryDialog({ open, onOpenChange, patientId, name }) {
  const qc = useQueryClient()
  const gen = useMutation({
    mutationFn: () => api.doctors.summary(patientId),
    onSuccess: () => qc.invalidateQueries({ queryKey: ['doctor', 'timeline', patientId] }),
  })
  const { mutate, data, isIdle } = gen

  useEffect(() => {
    if (open && isIdle) mutate()
  }, [open, isIdle, mutate])

  const copy = async () => {
    if (!data) return
    const text = [
      `Clinical summary — ${name}`,
      '',
      data.summary,
      '',
      'Key findings:',
      ...(data.key_findings || []).map((f) => `• ${f}`),
      '',
      'Recommendations:',
      ...(data.recommendations || []).map((f) => `• ${f}`),
    ].join('\n')
    try {
      await navigator.clipboard.writeText(text)
      toast.success('Summary copied')
    } catch {
      toast.error('Couldn’t access the clipboard')
    }
  }

  return (
    <Dialog
      open={open}
      onOpenChange={onOpenChange}
      size="lg"
      title="AI clinical summary"
      description={`Monitoring overview for ${name}. Decision support only — not a diagnosis.`}
      footer={
        <>
          <Button variant="ghost" icon={Copy} onClick={copy} disabled={!data}>Copy summary</Button>
          <Button variant="outline" icon={RefreshCw} loading={gen.isPending} onClick={() => gen.mutate()}>Regenerate</Button>
          <Button variant="primary" onClick={() => onOpenChange(false)}>Done</Button>
        </>
      }
    >
      {gen.isPending ? (
        <div className="space-y-4" aria-busy="true" aria-live="polite">
          <p className="flex items-center gap-2 font-mono text-[0.875rem] text-ink-3"><Sparkles aria-hidden strokeWidth={1.8} className="h-4 w-4 text-teal-700" /> Reading movement trends, medications and reports…</p>
          <Skeleton className="h-20" />
          <div className="grid gap-6 sm:grid-cols-2"><Skeleton className="h-32" /><Skeleton className="h-32" /></div>
        </div>
      ) : gen.isError ? (
        <ErrorState error={gen.error} onRetry={() => gen.mutate()} />
      ) : data ? (
        <motion.div initial={{ opacity: 0, y: 6 }} animate={{ opacity: 1, y: 0 }} transition={{ duration: 0.3, ease: [0.2, 0.8, 0.2, 1] }} className="space-y-6">
          <div className="flex flex-wrap items-center gap-2">
            <Badge tone={data.source === 'model' ? 'teal' : 'ink'} dot>{data.source === 'model' ? 'Generated by AI model' : 'Rule-based summary'}</Badge>
            {data.created_at && <span className="font-mono text-[0.8125rem] text-ink-3">{fmtDate(data.created_at, 'd MMM yyyy, HH:mm')}</span>}
          </div>
          <p className="max-w-[65ch] font-serif text-[1.3125rem] leading-snug text-ink text-pretty">{data.summary}</p>
          <div className="grid gap-6 sm:grid-cols-2">
            <List icon={ListChecks} title="Key findings" items={data.key_findings} />
            <List icon={Lightbulb} title="Recommendations" items={data.recommendations} />
          </div>
        </motion.div>
      ) : null}
    </Dialog>
  )
}

function List({ icon, title, items = [] }) {
  return (
    <section className="border-t border-line pt-3">
      <Label as="h3" icon={icon} className="mb-3">{title}</Label>
      {items.length ? (
        <ol className="space-y-2">
          {items.map((t, i) => (
            <li key={i} className="flex gap-3 text-[0.9375rem] leading-relaxed text-ink-2">
              <span className="num w-4 shrink-0 pt-px font-mono text-[0.8125rem] text-ink-4">{i + 1}</span>
              <span className="text-pretty">{t}</span>
            </li>
          ))}
        </ol>
      ) : <p className="text-[0.9375rem] text-ink-3">Nothing noted.</p>}
    </section>
  )
}
